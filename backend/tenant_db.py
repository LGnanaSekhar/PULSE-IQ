"""PULSEIQ 3 college-aware tables. Legacy v2 tables are not accessed by v3 APIs."""
from sqlalchemy import (MetaData, Table, Column, String, Integer, Float, Boolean,
    JSON, Date, DateTime, ForeignKey, UniqueConstraint, Index)
from .db import now, engine_for

metadata = MetaData()
colleges = Table('pi3_colleges', metadata,
    Column('id', String(36), primary_key=True),
    Column('name', String(150), nullable=False),
    Column('domain', String(150), unique=True, nullable=False),
    Column('created_at', DateTime(timezone=True), nullable=False))
accounts = Table('pi3_accounts', metadata,
    Column('id', String(36), primary_key=True),
    Column('college_id', ForeignKey('pi3_colleges.id'), nullable=False, index=True),
    Column('email', String(250), unique=True, nullable=False),
    Column('full_name', String(150), nullable=False),
    Column('password_hash', String(300), nullable=False),
    Column('role', String(20), nullable=False),
    Column('departments', JSON, nullable=False),
    Column('student_id', String(100)),
    Column('active', Boolean, nullable=False, default=True))
sessions = Table('pi3_sessions', metadata,
    Column('token_hash', String(64), primary_key=True),
    Column('user_id', ForeignKey('pi3_accounts.id'), nullable=False),
    Column('csrf_token', String(80), nullable=False),
    Column('expires_at', DateTime(timezone=True), nullable=False))
attempts = Table('pi3_attempts', metadata,
    Column('id', String(36), primary_key=True),
    Column('identity_hash', String(64), index=True),
    Column('at', DateTime(timezone=True), nullable=False))
roster = Table('pi3_roster', metadata,
    Column('id', String(36), primary_key=True),
    Column('college_id', ForeignKey('pi3_colleges.id'), nullable=False, index=True),
    Column('student_id', String(100), nullable=False),
    Column('full_name', String(150), nullable=False),
    Column('email', String(250)),
    Column('department', String(100), nullable=False),
    Column('semester', Integer, nullable=False),
    Column('section', String(50), nullable=False, default='A'),
    Column('active', Boolean, nullable=False, default=True),
    UniqueConstraint('college_id', 'student_id', name='pi3_roster_per_college'))
subjects = Table('pi3_assignments', metadata,
    Column('id', String(36), primary_key=True),
    Column('college_id', ForeignKey('pi3_colleges.id'), nullable=False),
    Column('faculty_id', ForeignKey('pi3_accounts.id'), nullable=False),
    Column('department', String(100), nullable=False),
    Column('semester', Integer, nullable=False),
    Column('section', String(50), nullable=False),
    Column('subject', String(150), nullable=False),
    UniqueConstraint('college_id', 'faculty_id','department','semester','section','subject', name='pi3_assign_unique'))
entries = Table('pi3_entries', metadata,
    Column('id', String(36), primary_key=True),
    Column('college_id', ForeignKey('pi3_colleges.id'), nullable=False),
    Column('roster_id', ForeignKey('pi3_roster.id'), nullable=False),
    Column('assignment_id', ForeignKey('pi3_assignments.id'), nullable=False),
    Column('kind', String(20), nullable=False),
    Column('period_end', Date, nullable=False),
    Column('attended', Integer), Column('held', Integer), Column('marks_pct', Float),
    Column('status', String(20), nullable=False),
    Column('updated_by', ForeignKey('pi3_accounts.id'), nullable=False),
    Column('updated_at', DateTime(timezone=True), nullable=False),
    UniqueConstraint('roster_id', 'assignment_id', 'kind', 'period_end',name='pi3_entries_unique'))
observations = Table('pi3_observations', metadata,
    Column('id', String(36), primary_key=True),
    Column('college_id', ForeignKey('pi3_colleges.id'), nullable=False, index=True),
    Column('roster_id', ForeignKey('pi3_roster.id'), nullable=False),
    Column('kind', String(30), nullable=False),
    Column('period_end', Date, nullable=False),
    Column('payload', JSON, nullable=False),
    Column('source_name', String(150), nullable=False),
    Column('created_at', DateTime(timezone=True), nullable=False),
    UniqueConstraint('roster_id','kind','period_end',name='pi3_observation_unique'))
actions = Table('pi3_actions', metadata,
    Column('id', String(36), primary_key=True),
    Column('college_id', ForeignKey('pi3_colleges.id'), nullable=False),
    Column('roster_id', ForeignKey('pi3_roster.id'), nullable=False),
    Column('owner', String(150), nullable=False),
    Column('action', String(2000), nullable=False),
    Column('status', String(30), nullable=False),
    Column('due_date', Date, nullable=False),
    Column('note', String(2000), nullable=False, default=''),
    Column('version', Integer, nullable=False),
    Column('updated_by', ForeignKey('pi3_accounts.id'), nullable=False),
    Column('updated_at', DateTime(timezone=True), nullable=False))
connections = Table('pi3_connections', metadata,
    Column('id', String(36), primary_key=True),
    Column('college_id', ForeignKey('pi3_colleges.id'), nullable=False),
    Column('name', String(150), nullable=False),
    Column('kind', String(20), nullable=False),
    Column('encrypted_dsn', String(6000), nullable=False),
    Column('mapping', JSON, nullable=False),
    Column('created_at', DateTime(timezone=True), nullable=False))
logs = Table('pi3_audit', metadata,
    Column('id', String(36), primary_key=True),
    Column('college_id', ForeignKey('pi3_colleges.id'), nullable=False, index=True),
    Column('actor_id', String(36)),
    Column('event', String(90), nullable=False),
    Column('details', JSON, nullable=False),
    Column('at', DateTime(timezone=True), nullable=False))
